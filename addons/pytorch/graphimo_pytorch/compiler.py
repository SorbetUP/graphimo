@dataclass(frozen=True, slots=True)
class CompileResult:
    generated_source: str
    factory: object
    bindings: RuntimeBindingMap
    shape_result: ShapeInferenceResult
    diagnostics: tuple[Diagnostic, ...]
    definition: PyTorchModelDefinition


_WRAPPERS = {
    "reshape": "ReshapeOp", "transpose": "TransposeOp", "split_heads": "SplitHeadsOp",
    "merge_heads": "MergeHeadsOp", "add": "AddOp", "multiply": "MultiplyOp", "scale": "ScaleOp",
    "matmul": "MatMulOp", "rope": "RoPEOp", "causal_mask": "CausalMaskOp",
    "concatenate": "ConcatenateOp", "unflatten": "UnflattenOp", "cross_entropy": "CrossEntropyOp",
}


def compile_model(
    state: PyTorchMetaBlockState,
    external_values: Mapping[str, JsonScalar] | None = None,
    *,
    compiler_version: str = __version__,
) -> CompileResult:
    """Compile trusted addon-generated Python; arbitrary source is never accepted."""
    external_values = external_values or {}
    declared = {item.id: item for item in state.external_parameters}
    diagnostics = list(validate_model_graph(state, external_values).diagnostics)
    for key in external_values.keys() - declared.keys():
        diagnostics.append(Diagnostic("pytorch_external_parameter_unknown", f"Unknown external parameter id {key!r}"))
    shape_result = infer_model_shapes(state, external_values)
    diagnostics.extend(shape_result.diagnostics)
    diagnostics = _unique_diagnostics(diagnostics)
    if any(item.severity == "error" for item in diagnostics):
        raise GraphimoPytorchError("pytorch_compile_invalid", _diagnostics_text(diagnostics))

    resolved = {parameter.id: external_values.get(parameter.id, parameter.default) for parameter in state.external_parameters}
    revision = graph_revision(state)
    materialization_payload = json.dumps(
        {"graph_revision": revision, "external_parameters": resolved, "compiler_version": compiler_version},
        ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False,
    )
    materialization_key = hashlib.sha256(materialization_payload.encode("utf-8")).hexdigest()
    class_name = _python_name(state.name, fallback="GraphimoModel")
    group_classes = {group.id: _group_class_name(group) for group in state.groups}
    source, bindings = _generate_source(state, shape_result, revision, materialization_key, class_name, group_classes, resolved)
    namespace: dict[str, object] = {
        "__builtins__": {"__import__": __import__, "__build_class__": builtins.__build_class__,
                         "range": range, "len": len, "super": super, "object": object},
        "__name__": "graphimo_pytorch_generated",
    }
    try:
        code = compile(source, f"<graphimo-pytorch:{state.metablock_id}>", "exec")
        exec(code, namespace)
        factory = namespace[class_name]
    except Exception as error:
        raise GraphimoPytorchError(
            "pytorch_codegen_failed",
            f"Generated PyTorch source failed to compile: {type(error).__name__}: {error}\n\n{source}",
        ) from error
    definition = PyTorchModelDefinition(
        state.metablock_id, revision, materialization_key, state.name, source, resolved, bindings, factory
    )
    return CompileResult(source, factory, bindings, shape_result, tuple(diagnostics), definition)


def _generate_source(
    state: PyTorchMetaBlockState, shapes: ShapeInferenceResult, revision: str, materialization_key: str,
    model_class: str, group_classes: Mapping[str, str], external: Mapping[str, JsonScalar],
) -> tuple[str, RuntimeBindingMap]:
    kinds = {element.kind for method in state.entrypoints for element in method.elements}
    for group in state.groups:
        kinds.update(element.kind for element in group.elements)
    imports = sorted({_WRAPPERS[kind] for kind in kinds if kind in _WRAPPERS})
    lines = [
        "# Generated by graphimo-pytorch",
        f"# graphimo-metablock-id: {state.metablock_id}",
        f"# graphimo-graph-revision: {revision}",
        f"# graphimo-materialization-key: {materialization_key}",
        "import torch",
        "import torch.nn as nn",
    ]
    if imports:
        lines.append("from graphimo_pytorch.runtime_ops import " + ", ".join(imports))
    lines.append("")
    for group in state.groups:
        lines.extend(_render_scope_class(
            group.name, group_classes[group.id], group.elements, group.edges, group.group_instances,
            group.inputs, group.outputs, group_classes, state.groups, shapes, external, method_prefix="",
        ))
        lines.append("")
    lines.extend(_render_model_class(state, model_class, group_classes, shapes, external))
    binding_sites = _binding_sites(state, group_classes)
    return "\n".join(lines).rstrip() + "\n", RuntimeBindingMap(tuple(binding_sites))


def _render_model_class(
    state: PyTorchMetaBlockState, class_name: str, group_classes: Mapping[str, str],
    shapes: ShapeInferenceResult, external: Mapping[str, JsonScalar],
) -> list[str]:
    lines = [f"class {class_name}(nn.Module):", "    def __init__(self):", "        super().__init__()"]
    if not state.entrypoints:
        lines.append("        pass")
    for method in state.entrypoints:
        prefix = "" if method.name == "forward" else f"{method.name}_"
        lines.extend(_render_scope_initializers(
            method.elements, method.group_instances, prefix, group_classes, state.groups, shapes, external, indent="        ",
            edges=method.edges,
        ))
    for method in state.entrypoints:
        lines.append("")
        if method.name == "predict":
            lines.append("    @torch.no_grad()")
        lines.extend(_render_scope_method(
            method.name, method.elements, method.edges, method.group_instances, method.inputs, method.outputs,
            (), (), group_classes, state.groups, shapes, external, method_prefix="" if method.name == "forward" else f"{method.name}_",
        ))
    return lines


def _render_scope_class(
    display_name: str, class_name: str, elements: tuple[ElementRecord, ...], edges: tuple[object, ...],
    instances: tuple[GroupInstance, ...], inputs: tuple[object, ...], outputs: tuple[object, ...],
    group_classes: Mapping[str, str], groups: tuple[GroupDefinition, ...], shapes: ShapeInferenceResult,
    external: Mapping[str, JsonScalar], method_prefix: str,
) -> list[str]:
    lines = [f"class {class_name}(nn.Module):", "    def __init__(self):", "        super().__init__()"]
    lines.extend(_render_scope_initializers(
        elements, instances, method_prefix, group_classes, groups, shapes, external, indent="        ", edges=edges,
    ))
    lines.append("")
    lines.extend(_render_scope_method(
        "forward", elements, edges, instances, (), (), inputs, outputs, group_classes, groups,
        shapes, external, method_prefix,
    ))
    return lines


def _render_scope_initializers(
    elements: tuple[ElementRecord, ...], instances: tuple[GroupInstance, ...], prefix: str,
    group_classes: Mapping[str, str], groups: tuple[GroupDefinition, ...], shapes: ShapeInferenceResult,
    external: Mapping[str, JsonScalar], *, indent: str, edges: tuple[object, ...],
) -> list[str]:
    lines: list[str] = []
    for instance in instances:
        class_name = group_classes.get(instance.group_id)
        if class_name is None:
            continue
        attribute = prefix + _python_name(instance.name, fallback="group")
        if instance.repeat == 1:
            lines.append(f"{indent}self.{attribute} = {class_name}()")
        else:
            lines.append(f"{indent}self.{attribute} = nn.ModuleList([{class_name}() for _ in range({instance.repeat})])")
    for element in elements:
        if element.kind in {"input", "output", "group_instance", "method_call"}:
            continue
        params = _params_for(element, external)
        expression = _module_constructor(element, params, shapes, edges)
        if expression:
            attribute = prefix + _python_name(element.name, fallback="layer")
            lines.append(f"{indent}self.{attribute} = {expression}")
            if element.kind == "embedding" and params.get("init_std") is not None:
                lines.append(f"{indent}nn.init.normal_(self.{attribute}.weight, mean=0.0, std={_literal(params['init_std'])})")
            if element.kind == "linear" and params.get("init_std") is not None:
                lines.append(f"{indent}nn.init.normal_(self.{attribute}.weight, mean=0.0, std={_literal(params['init_std'])})")
    return lines or [f"{indent}pass"]


def _render_scope_method(
    method_name: str, elements: tuple[ElementRecord, ...], edges: tuple[object, ...], instances: tuple[GroupInstance, ...],
    method_inputs: tuple[object, ...], method_outputs: tuple[object, ...], group_inputs: tuple[object, ...],
    group_outputs: tuple[object, ...], group_classes: Mapping[str, str], groups: tuple[GroupDefinition, ...],
    shapes: ShapeInferenceResult, external: Mapping[str, JsonScalar], method_prefix: str,
) -> list[str]:
    inputs = method_inputs or group_inputs
    input_names = [_python_name(item.name, fallback=f"input_{index}") for index, item in enumerate(inputs)]
    signature = ", ".join(["self", *input_names])
    lines = [f"    def {method_name}({signature}):"]
    boundary_values = {item.id: input_names[index] for index, item in enumerate(inputs)}
    by_id = {item.id: item for item in elements}
    instance_by_id = {item.id: item for item in instances}
    groups_by_id = {item.id: item for item in groups}
    adjacency: dict[str, list[str]] = {node: [] for node in [*by_id, *instance_by_id]}
    indegree = {node: 0 for node in adjacency}
    for edge in edges:
        if edge.source.element_id in adjacency and edge.target.element_id in adjacency:
            adjacency[edge.source.element_id].append(edge.target.element_id)
            indegree[edge.target.element_id] += 1
    order: list[str] = []
    ready = [node for node, count in indegree.items() if count == 0]
    while ready:
        node = ready.pop(0)
        order.append(node)
        for target in adjacency[node]:
            indegree[target] -= 1
            if indegree[target] == 0:
                ready.append(target)
    expressions: dict[tuple[str, str], str] = {}
    for element in elements:
        if element.kind == "input":
            method_input = element.params.get("method_input")
            if method_input in boundary_values:
                expressions[(element.id, "out")] = boundary_values[method_input]
    body: list[str] = []
    output_expressions: dict[str, str] = {}
    for node_id in order:
        element = by_id.get(node_id)
        if element is not None:
            if element.kind in {"input", "output"}:
                if element.kind == "output":
                    source = _edge_source(edges, node_id, "x")
                    expression = _source_expression(source, expressions, boundary_values)
                    if expression is not None:
                        output_expressions[str(element.params.get("method_output"))] = expression
                continue
            refs = _incoming_expressions(element.kind, node_id, edges, expressions, boundary_values)
            args = ", ".join(refs)
            temp = _temp(node_id)
            if element.kind == "method_call":
                method_name = _python_name(str(element.params["method"]), "method")
                body.append(f"{temp} = self.{method_name}({args})")
                expressions[(node_id, "out")] = temp
                continue
            body.append(f"{temp} = self.{method_prefix}{_python_name(element.name, 'layer')}({args})")
            expressions[(node_id, "out")] = temp
            continue
        instance = instance_by_id[node_id]
        definition = groups_by_id[instance.group_id]
        refs = []
        for port in definition.inputs:
            source = _edge_source(edges, instance.id, port.name)
            value = _source_expression(source, expressions, boundary_values)
            if value is not None:
                refs.append(value)
        attribute = method_prefix + _python_name(instance.name, "group")
        temp = _temp(instance.id)
        if instance.repeat == 1:
            body.append(f"{temp} = self.{attribute}({', '.join(refs)})")
        else:
            initial = refs[0] if len(refs) == 1 else "(" + ", ".join(refs) + ("," if len(refs) == 1 else "") + ")"
            body.append(f"{temp} = {initial}")
            loop_name = f"_graphimo_layer_{_stable_suffix(instance.id)}"
            body.append(f"for {loop_name} in self.{attribute}:")
            call = f"{loop_name}(*{temp})" if len(definition.inputs) > 1 else f"{loop_name}({temp})"
            body.append(f"    {temp} = {call}")
        for index, port in enumerate(definition.outputs):
            expression = temp if len(definition.outputs) == 1 else f"{temp}[{index}]"
            expressions[(instance.id, port.name)] = expression
    for port in group_outputs:
        source = _edge_source(edges, port.id, "x")
        expression = _source_expression(source, expressions, boundary_values)
        if expression is not None:
            output_expressions[port.id] = expression
    body_lines = body or ["pass"]
    lines.extend("        " + line if not line.startswith("    ") else "        " + line for line in body_lines)
    return_ids = [item.id for item in (method_outputs or group_outputs)]
    returned = [output_expressions[item] for item in return_ids if item in output_expressions]
    if returned:
        value = returned[0] if len(returned) == 1 else "(" + ", ".join(returned) + ")"
        lines.append(f"        return {value}")
    elif not body:
        lines.append("        return None")
    return lines


def _module_constructor(element: ElementRecord, params: Mapping[str, object], shapes: ShapeInferenceResult,
                        edges: tuple[object, ...]) -> str | None:
    kind = element.kind
    if kind == "embedding":
        return f"nn.Embedding({params['num_embeddings']}, {params['embedding_dim']})"
    if kind == "linear":
        return f"nn.Linear({params['in_features']}, {params['out_features']}, bias={_literal(params.get('bias', True))})"
    if kind == "rms_norm":
        return f"nn.RMSNorm({params['normalized_shape']}, eps={_literal(params.get('eps', 1e-5))})"
    if kind == "dropout":
        return f"nn.Dropout(p={_literal(params['p'])})"
    if kind == "relu":
        return "nn.ReLU()"
    if kind == "gelu":
        return "nn.GELU()"
    if kind == "silu":
        return "nn.SiLU()"
    if kind == "softmax":
        return f"nn.Softmax(dim={params.get('dim', -1)})"
    if kind == "flatten":
        return f"nn.Flatten(start_dim={params.get('start_dim', 0)}, end_dim={params.get('end_dim', -1)})"
    if kind == "reshape":
        return f"ReshapeOp({_literal(tuple(params['target_shape']))}, {_literal(_source_symbols(element.id, edges, shapes))})"
    if kind == "transpose":
        return f"TransposeOp({params['dim0']}, {params['dim1']})"
    if kind == "split_heads":
        return f"SplitHeadsOp({params['n_heads']})"
    if kind == "merge_heads":
        return "MergeHeadsOp()"
    if kind == "add":
        return "AddOp()"
    if kind == "multiply":
        return "MultiplyOp()"
    if kind == "scale":
        return f"ScaleOp({_literal(params['factor'])})"
    if kind == "matmul":
        return "MatMulOp()"
    if kind == "rope":
        return f"RoPEOp(base={_literal(params.get('base', 10000.0))})"
    if kind == "causal_mask":
        return "CausalMaskOp()"
    if kind == "concatenate":
        return f"ConcatenateOp(dim={params.get('dim', 0)})"
    if kind == "unflatten":
        return f"UnflattenOp({params['dim']}, {_literal(tuple(params['sizes']))}, {_literal(_source_symbols(element.id, edges, shapes))})"
    if kind == "cross_entropy":
        return f"CrossEntropyOp(mode={_literal(params.get('mode', 'generic'))})"
    raise GraphimoPytorchError("pytorch_element_compiler_missing", f"No module compiler for {kind!r}")


def _source_symbols(element_id: str, edges: tuple[object, ...], shapes: ShapeInferenceResult) -> tuple[str, ...]:
    incoming = next((edge for edge in edges if edge.target.element_id == element_id), None)
    if incoming is None:
        return ()
    key_suffix = f":{incoming.id}"
    spec = next((value for key, value in shapes.edge_specs.items() if key.endswith(key_suffix)), None)
    return tuple(dim.expr for dim in spec.shape) if spec is not None else ()


def _incoming_expressions(kind: str, node_id: str, edges: tuple[object, ...],
                          expressions: Mapping[tuple[str, str], str], boundaries: Mapping[str, str]) -> list[str]:
    targets = [edge for edge in edges if edge.target.element_id == node_id]
    if kind in {"add", "multiply", "matmul"}:
        targets.sort(key=lambda edge: ("a", "b").index(edge.target.port) if edge.target.port in {"a", "b"} else 99)
    elif kind == "cross_entropy":
        targets.sort(key=lambda edge: ("logits", "target").index(edge.target.port) if edge.target.port in {"logits", "target"} else 99)
    elif kind == "concatenate":
        targets.sort(key=lambda edge: _variadic_index(edge.target.port))
    else:
        targets.sort(key=lambda edge: edge.target.port)
    result = []
    for edge in targets:
        value = _source_expression((edge.source.element_id, edge.source.port), expressions, boundaries)
        if value is not None:
            result.append(value)
    return result


def _edge_source(edges: tuple[object, ...], target_id: str, target_port: str) -> tuple[str, str] | None:
    for edge in edges:
        if edge.target.element_id == target_id and edge.target.port == target_port:
            return edge.source.element_id, edge.source.port
    return None


def _source_expression(source: tuple[str, str] | None, expressions: Mapping[tuple[str, str], str],
                       boundaries: Mapping[str, str]) -> str | None:
    if source is None:
        return None
    return expressions.get(source) or (boundaries.get(source[0]) if source[1] == "out" else None)


def _binding_sites(state: PyTorchMetaBlockState, group_classes: Mapping[str, str]) -> list[RuntimeSite]:
    result: list[RuntimeSite] = []
    groups = {group.id: group for group in state.groups}
    for method in state.entrypoints:
        prefix = "" if method.name == "forward" else f"{method.name}_"
        _walk_sites(method.elements, method.group_instances, prefix, (), groups, result)
    return result


def _walk_sites(elements: tuple[ElementRecord, ...], instances: tuple[GroupInstance, ...], prefix: str,
                group_path: tuple[GroupRuntimeIndex, ...], groups: Mapping[str, GroupDefinition], output: list[RuntimeSite]) -> None:
    for element in elements:
        if element.kind not in {"input", "output", "method_call"}:
            output.append(RuntimeSite(element.id, prefix + _python_name(element.name, "layer"), group_path, True))
    for instance in instances:
        group = groups.get(instance.group_id)
        if group is None:
            continue
        for repetition in range(instance.repeat):
            path_index = GroupRuntimeIndex(instance.id, repetition)
            path = group_path + (path_index,)
            module_path = prefix + _python_name(instance.name, "group") + (f".{repetition}" if instance.repeat > 1 else "")
            output.append(RuntimeSite(instance.id, module_path, path, True))
            _walk_sites(group.elements, group.group_instances, module_path + ".", path, groups, output)


def _params_for(element: ElementRecord, external: Mapping[str, JsonScalar]) -> dict[str, object]:
    params: dict[str, object] = dict(element.params)
    # Bindings have already been checked by validate_model_graph.
    # The caller's state is available on the element; external resolution is performed in compile_model.
    for name, binding in element.parameter_bindings.items():
        if binding.external_parameter_id in external:
            params[name] = external[binding.external_parameter_id]
    defaults = {
        "bias": True, "eps": 1e-5, "p": 0.5, "dim": -1, "start_dim": 0,
        "end_dim": -1, "layout": "e_t_d_to_e_h_t_dh", "base": 10000.0, "mode": "generic",
    }
    for key, value in defaults.items():
        params.setdefault(key, value)
    return params


def _python_name(value: str, fallback: str) -> str:
    cleaned = re.sub(r"\W+", "_", value).strip("_")
    if not cleaned or cleaned[0].isdigit():
        cleaned = f"{fallback}_{cleaned}" if cleaned else fallback
    if keyword.iskeyword(cleaned):
        cleaned += "_"
    return cleaned


def _group_class_name(group: GroupDefinition) -> str:
    return f"GraphimoGroup_{_python_name(group.name, 'Group')}_{_stable_suffix(group.id)}"


def _stable_suffix(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:8]


def _temp(node_id: str) -> str:
    return f"_graphimo_value_{_stable_suffix(node_id)}"


def _variadic_index(port: str) -> int:
    match = re.fullmatch(r"inputs\[(\d+)\]", port)
    return int(match.group(1)) if match else 0


def _literal(value: object) -> str:
    if isinstance(value, tuple):
        return "(" + ", ".join(_literal(item) for item in value) + ("," if len(value) == 1 else "") + ")"
    if isinstance(value, list):
        return "[" + ", ".join(_literal(item) for item in value) + "]"
    return repr(value)


def _diagnostics_text(diagnostics: list[Diagnostic]) -> str:
    return "Graph cannot be compiled:\n" + "\n".join(f"- {item.code}: {item.message}" for item in diagnostics if item.severity == "error")


def _unique_diagnostics(diagnostics: list[Diagnostic]) -> list[Diagnostic]:
    unique: list[Diagnostic] = []
    seen: set[tuple[str, str, str | None]] = set()
    for item in diagnostics:
        key = (item.code, item.message, item.element_id)
        if key not in seen:
            unique.append(item)
            seen.add(key)
    return unique

